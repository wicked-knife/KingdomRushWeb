"""Export/serve the menu, KR1 map, hero room and campaigns 1-4 with explicit manifests."""
import argparse
import functools
import http.server
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "data/menu_manifest.json"


def resource_paths():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if manifest["schema_version"] != 1:
        raise ValueError("Unsupported menu manifest")
    resources = [*manifest["scenes"], *manifest["scripts"], *manifest.get("fonts", [manifest["font"]]), manifest["background"], *manifest["textures"], *manifest["audio"].values()]
    data = ["res://data/menu_manifest.json", manifest["catalog"], manifest["locale"], manifest["sounds"], manifest["font_roles"], *manifest["atlases"].values()]
    for level_id in (1, 2, 3, 4):
        level_name = f"level{level_id:02d}"
        level = json.loads((ROOT / f"data/{level_name}/manifest.json").read_text(encoding="utf-8"))
        resources += level["resources"]
        data += level["data"] + [f"res://data/{level_name}/manifest.json"]
    resources += ["res://scripts/services/campaign_levels.gd", "res://scripts/battle/level01_sim.gd", "res://scripts/battle/battle_view.gd", "res://scripts/battle/battle_ui.gd", "res://scripts/battle/dove_ui_layout.gd", "res://scripts/battle/dove_animation.gd", "res://scripts/battle/dove_projectile.gd", "res://scripts/battle/dove_unit_info.gd", "res://scripts/battle/battle_developer.gd"]
    resources += ["res://scripts/battle/battle_wave_flags.gd", "res://scripts/map/dove_map_flag.gd"]
    campaign_map = json.loads((ROOT / "data/map_kr1/manifest.json").read_text(encoding="utf-8"))
    resources += campaign_map["resources"]
    data += campaign_map["data"] + ["res://data/map_kr1/manifest.json"]
    heroes = json.loads((ROOT / "data/heroes/manifest.json").read_text(encoding="utf-8"))
    resources += heroes["resources"]
    data += heroes["data"] + ["res://data/heroes/manifest.json"]
    resources = list(dict.fromkeys(resources)); data = list(dict.fromkeys(data))
    for path in resources + data:
        local = (ROOT / path.removeprefix("res://")).resolve()
        if not path.startswith("res://") or not local.is_relative_to(ROOT) or not local.is_file():
            raise ValueError(f"Invalid or missing bootstrap resource: {path}")
    return resources, data


