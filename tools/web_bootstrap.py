def godot_path(explicit=None):
    candidates = [explicit, shutil.which("godot"), shutil.which("godot4"), "D:/godot/Godot_v4.7.2-stable_win64_console.exe"]
    executable = next((p for p in candidates if p and Path(p).is_file()), None)
    if not executable:
        raise RuntimeError("Godot not found. Pass --godot PATH.")
    version = subprocess.check_output([executable, "--version"], text=True).strip()
    if not version.startswith("4.7.2.stable"):
        raise RuntimeError(f"Expected Godot 4.7.2 stable, found {version}")
    return executable


class Handler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map, ".wasm": "application/wasm", ".pck": "application/octet-stream", ".js": "text/javascript", ".json": "application/json"}

    def end_headers(self):
        # Avoid stale local builds; no service worker or cross-origin isolation needed.
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["preset", "export", "serve"])
    parser.add_argument("--godot")
    parser.add_argument("--debug", action="store_true", help="Export a debug playtest with the developer menu (F8)")
    parser.add_argument("--port", type=int, default=8060)
    parser.add_argument("--check-pack", action="store_true", help="Opt in to the isolated Godot PCK check after export; never opens a browser")
    args = parser.parse_args()
    if args.command in ("preset", "export"):
        (ROOT / "export_presets.cfg").write_text(preset_text(), encoding="utf-8")
    if args.command == "export":
        engine = godot_path(args.godot)
        output = ROOT / "build/web/index.html"
        output.parent.mkdir(parents=True, exist_ok=True)
        # Keep generated artifacts and the isolated verification project out of the editor.
        (ROOT / "build/.gdignore").touch()
        # An earlier build's verification must never be presented as this build's result.
        for name in ("pack_files.json", "export_receipt.json"):
            (output.parent / name).unlink(missing_ok=True)
        subprocess.run([engine, "--headless", "--path", str(ROOT), "--export-debug" if args.debug else "--export-release", "Web Bootstrap", str(output)], check=True)
        if args.check_pack:
            subprocess.run([engine, "--headless", "--path", str(ROOT), "--script", "res://tests/verify_web_pack.gd", "--", str(output.with_suffix(".pck"))], check=True)
        receipt = {
            "export_succeeded": True,
            "build_type": "debug" if args.debug else "release",
            "developer_menu": args.debug,
            "includes_kr1_map": True,
            "includes_hero_room": True,
            "playable_levels": [1, 2, 3, 4],
            "pck_sha256": hashlib.sha256(output.with_suffix(".pck").read_bytes()).hexdigest(),
            "pck_isolated_check": args.check_pack,
            "browser_tested": False,
        }
        (output.parent / "export_receipt.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
        print(f"Export complete ({'PCK checked' if args.check_pack else 'no Web validation'}): {output}")
    if args.command == "serve":
        directory = ROOT / "build/web"
        if not (directory / "index.html").is_file():
            parser.error("Run 'python tools/web_bootstrap.py export' first.")
        handler = functools.partial(Handler, directory=str(directory))
        with http.server.ThreadingHTTPServer(("127.0.0.1", args.port), handler) as server:
            print(f"Open http://127.0.0.1:{args.port}/ (Ctrl+C to stop)", flush=True)
            try:
                server.serve_forever()
            except KeyboardInterrupt:
                pass


if __name__ == "__main__":
    main()
